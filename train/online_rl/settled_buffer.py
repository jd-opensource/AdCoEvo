"""Causal, single-use settled-record buffers for role-rotated co-evolution.

The collector keeps one buffer per role. A scheduled round consumes the oldest
eligible homogeneous behavior-policy version so the existing learner can
recompute its behavior log-probabilities with one adapter. Newer records stay
buffered for the next round.
"""

from __future__ import annotations

import copy
import hashlib
import json
from typing import Any

from train.online_rl.schema import ROLES, OnlineTrajectory


def empty_buffers() -> dict[str, list[dict[str, Any]]]:
    return {role: [] for role in ROLES}


def settled_role_record(trajectory: OnlineTrajectory, role: str) -> dict[str, Any]:
    """Retain only a role's settled nodes from a completed trajectory."""
    if role not in ROLES:
        raise ValueError(f"unknown role: {role}")
    if role == "inspector" and not all(
        transition.terminal for transition in trajectory.transitions
        if transition.role == role
    ):
        raise ValueError("Inspector feedback has not settled yet")
    record = trajectory.to_dict()
    record["transitions"] = [transition for transition in record["transitions"]
                             if transition["role"] == role]
    if not record["transitions"]:
        raise ValueError(f"trajectory has no {role} records")
    return record


def append_record(buffers: dict[str, list[dict[str, Any]]], role: str,
                  record: dict[str, Any]) -> None:
    """Append once, including during a replay of an interrupted collection."""
    if role not in ROLES:
        raise ValueError(f"unknown role: {role}")
    if any(item["trajectory_id"] == record["trajectory_id"] for item in buffers[role]):
        return
    if not record["transitions"] or any(node["role"] != role for node in record["transitions"]):
        raise ValueError("buffer record must contain only the target role")
    buffers[role].append(copy.deepcopy(record))


def select_batch(buffers: dict[str, list[dict[str, Any]]], role: str,
                 current_version: int, current_episode: int,
                 max_lag: int = 2) -> tuple[dict[str, Any] | None, list[dict[str, Any]]]:
    """Consume the oldest eligible version; retain newer records.

    The returned batch is one queue message and thus one scheduled learner round.
    Records older than the learner's policy-lag limit are explicitly reported
    as discarded. Invalid actions remain in the settled sequence for critic
    training and temporal credit, although they do not update the Actor.
    """
    if role not in ROLES or max_lag < 0:
        raise ValueError("invalid role or max_lag")
    records = buffers[role]
    retained: list[dict[str, Any]] = []
    dropped: list[dict[str, Any]] = []
    for record in records:
        version = int(record["role_policy_versions"][role])
        episode = int(record["episode"])
        if episode > current_episode:
            raise ValueError("future-period record in settled buffer")
        if version > current_version:
            raise ValueError("buffer record generated by a future policy version")
        if current_version - version > max_lag:
            dropped.append({"trajectory_id": record["trajectory_id"],
                            "reason": "stale_behavior_policy", "version": version})
        else:
            retained.append(record)

    if retained:
        chosen_version = min(int(record["role_policy_versions"][role]) for record in retained)
        selected = [record for record in retained
                    if int(record["role_policy_versions"][role]) == chosen_version]
        remaining = [record for record in retained if record not in selected]
    else:
        buffers[role] = retained
        return None, dropped

    source_ids = [record["trajectory_id"] for record in selected]
    base = copy.deepcopy(selected[-1])
    base["transitions"] = [copy.deepcopy(node) for record in selected
                           for node in record["transitions"]]
    batch_key = json.dumps({"role": role, "sources": source_ids},
                           sort_keys=True, separators=(",", ":"))
    base["trajectory_id"] = "batch_" + hashlib.sha256(batch_key.encode()).hexdigest()[:24]
    base["role_policy_versions"][role] = chosen_version
    base["reward_config"]["settled_batch"] = {
        "role": role, "source_trajectory_ids": source_ids,
        "source_episodes": [int(record["episode"]) for record in selected],
    }
    OnlineTrajectory.from_dict(base)
    buffers[role] = remaining
    return base, dropped
